-- View status perangkat. Ambang 60 detik adalah nilai awal yang dapat disesuaikan.
CREATE OR REPLACE VIEW v_device_connection_status AS
SELECT
    device_id,
    device_code,
    device_type,
    device_name,
    ip_address,
    last_seen_at,
    CASE
        WHEN last_seen_at IS NULL THEN 'unknown'
        WHEN last_seen_at >= CURRENT_TIMESTAMP - INTERVAL '60 seconds' THEN 'online'
        ELSE 'offline'
    END AS connection_status
FROM devices
WHERE is_enabled = TRUE;

