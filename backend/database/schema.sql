-- 1. Perangkat yang terhubung ke sistem
CREATE TABLE IF NOT EXISTS devices (
    device_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code         VARCHAR(40) NOT NULL UNIQUE,
    device_type         VARCHAR(30) NOT NULL
                        CHECK (device_type IN ('server_ml', 'esp32_cam', 'esp32_controller')),
    device_name         VARCHAR(100) NOT NULL,
    ip_address          INET,
    firmware_version    VARCHAR(40),
    last_seen_at        TIMESTAMPTZ,
    is_enabled          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Heartbeat untuk mengetahui kapan perangkat terakhir terhubung
CREATE TABLE IF NOT EXISTS device_heartbeats (
    heartbeat_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id           BIGINT NOT NULL REFERENCES devices(device_id) ON DELETE CASCADE,
    ip_address          INET,
    wifi_rssi           SMALLINT,
    received_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Pengaturan AI dan pengoperasian robot (satu konfigurasi aktif)
CREATE TABLE IF NOT EXISTS robot_settings (
    setting_id                  SMALLINT PRIMARY KEY DEFAULT 1 CHECK (setting_id = 1),
    robot_name                  VARCHAR(80) NOT NULL DEFAULT 'SmartMop-01',
    operation_mode              VARCHAR(20) NOT NULL DEFAULT 'automatic'
                                CHECK (operation_mode IN ('automatic', 'manual')),
    camera_interval_seconds     SMALLINT NOT NULL DEFAULT 3
                                CHECK (camera_interval_seconds BETWEEN 1 AND 60),
    confidence_threshold        NUMERIC(4,3) NOT NULL DEFAULT 0.650
                                CHECK (confidence_threshold BETWEEN 0 AND 1),
    confirmation_frames         SMALLINT NOT NULL DEFAULT 3
                                CHECK (confirmation_frames BETWEEN 1 AND 10),
    movement_speed              VARCHAR(10) NOT NULL DEFAULT 'slow'
                                CHECK (movement_speed IN ('slow', 'medium', 'fast')),
    mop_duration_seconds        SMALLINT NOT NULL DEFAULT 10
                                CHECK (mop_duration_seconds BETWEEN 1 AND 300),
    cleaning_repeats            SMALLINT NOT NULL DEFAULT 2
                                CHECK (cleaning_repeats BETWEEN 1 AND 5),
    soap_volume_preset          VARCHAR(10) NOT NULL DEFAULT 'medium'
                                CHECK (soap_volume_preset IN ('low', 'medium', 'high')),
    dashboard_refresh_seconds   SMALLINT NOT NULL DEFAULT 5
                                CHECK (dashboard_refresh_seconds BETWEEN 1 AND 60),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Preferensi notifikasi (satu konfigurasi untuk prototipe)
CREATE TABLE IF NOT EXISTS notification_settings (
    notification_setting_id SMALLINT PRIMARY KEY DEFAULT 1
                             CHECK (notification_setting_id = 1),
    website_notification     BOOLEAN NOT NULL DEFAULT TRUE,
    sound_notification       BOOLEAN NOT NULL DEFAULT TRUE,
    browser_notification     BOOLEAN NOT NULL DEFAULT FALSE,
    spill_detected           BOOLEAN NOT NULL DEFAULT TRUE,
    cleaning_completed       BOOLEAN NOT NULL DEFAULT TRUE,
    system_error             BOOLEAN NOT NULL DEFAULT TRUE,
    low_battery              BOOLEAN NOT NULL DEFAULT TRUE,
    low_soap                 BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Hasil deteksi dari model ML
-- Bounding box disimpan dalam koordinat ternormalisasi 0 sampai 1.
CREATE TABLE IF NOT EXISTS detections (
    detection_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_device_id    BIGINT REFERENCES devices(device_id) ON DELETE SET NULL,
    detected_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    class_name          VARCHAR(80) NOT NULL,
    confidence          NUMERIC(5,4) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    bbox_x              NUMERIC(8,6) CHECK (bbox_x BETWEEN 0 AND 1),
    bbox_y              NUMERIC(8,6) CHECK (bbox_y BETWEEN 0 AND 1),
    bbox_width          NUMERIC(8,6) CHECK (bbox_width BETWEEN 0 AND 1),
    bbox_height         NUMERIC(8,6) CHECK (bbox_height BETWEEN 0 AND 1),
    image_path          TEXT,
    model_name          VARCHAR(100),
    model_version       VARCHAR(50),
    inference_ms        INTEGER CHECK (inference_ms IS NULL OR inference_ms >= 0),
    decision_status     VARCHAR(20) NOT NULL DEFAULT 'accepted'
                        CHECK (decision_status IN ('accepted', 'rejected', 'review')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. Sesi pembersihan yang dipicu deteksi atau dijalankan manual
CREATE TABLE IF NOT EXISTS cleaning_sessions (
    session_id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detection_id                BIGINT REFERENCES detections(detection_id) ON DELETE SET NULL,
    controller_device_id        BIGINT REFERENCES devices(device_id) ON DELETE SET NULL,
    operation_mode              VARCHAR(20) NOT NULL
                                CHECK (operation_mode IN ('automatic', 'manual')),
    session_status              VARCHAR(20) NOT NULL DEFAULT 'pending'
                                CHECK (session_status IN (
                                    'pending', 'approaching', 'mopping', 'verifying',
                                    'completed', 'failed', 'cancelled'
                                )),
    started_at                  TIMESTAMPTZ,
    completed_at                TIMESTAMPTZ,
    mop_duration_seconds        INTEGER CHECK (mop_duration_seconds IS NULL OR mop_duration_seconds >= 0),
    cleaning_attempts            SMALLINT NOT NULL DEFAULT 0 CHECK (cleaning_attempts >= 0),
    soap_pump_duration_ms       INTEGER CHECK (soap_pump_duration_ms IS NULL OR soap_pump_duration_ms >= 0),
    verification_result         VARCHAR(20)
                                CHECK (verification_result IN ('clean', 'still_dirty', 'uncertain')),
    verification_confidence     NUMERIC(5,4)
                                CHECK (verification_confidence IS NULL OR verification_confidence BETWEEN 0 AND 1),
    notes                       TEXT,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (completed_at IS NULL OR started_at IS NULL OR completed_at >= started_at)
);

-- 7. Perintah server kepada ESP32 DevKit
CREATE TABLE IF NOT EXISTS robot_commands (
    command_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id           BIGINT REFERENCES devices(device_id) ON DELETE SET NULL,
    session_id          BIGINT REFERENCES cleaning_sessions(session_id) ON DELETE SET NULL,
    command_type        VARCHAR(50) NOT NULL,
    command_payload     JSONB NOT NULL DEFAULT '{}'::jsonb,
    command_status      VARCHAR(20) NOT NULL DEFAULT 'queued'
                        CHECK (command_status IN ('queued', 'sent', 'acknowledged', 'failed')),
    response_payload    JSONB,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at             TIMESTAMPTZ,
    acknowledged_at     TIMESTAMPTZ
);

-- 8. Log aktivitas sistem untuk dashboard
CREATE TABLE IF NOT EXISTS activity_logs (
    log_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type          VARCHAR(50) NOT NULL,
    severity            VARCHAR(10) NOT NULL DEFAULT 'info'
                        CHECK (severity IN ('info', 'warning', 'error')),
    message             TEXT NOT NULL,
    detection_id        BIGINT REFERENCES detections(detection_id) ON DELETE SET NULL,
    session_id          BIGINT REFERENCES cleaning_sessions(session_id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. Telemetri perangkat (opsional; isi hanya jika data sensor tersedia)
CREATE TABLE IF NOT EXISTS device_telemetry (
    telemetry_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id           BIGINT NOT NULL REFERENCES devices(device_id) ON DELETE CASCADE,
    battery_voltage     NUMERIC(6,3) CHECK (battery_voltage IS NULL OR battery_voltage >= 0),
    battery_percent     NUMERIC(5,2) CHECK (battery_percent IS NULL OR battery_percent BETWEEN 0 AND 100),
    soap_level_percent  NUMERIC(5,2) CHECK (soap_level_percent IS NULL OR soap_level_percent BETWEEN 0 AND 100),
    soap_available      BOOLEAN,
    wifi_rssi           SMALLINT,
    measured_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Index untuk mempercepat pencarian riwayat berdasarkan waktu dan relasi.
CREATE INDEX IF NOT EXISTS idx_heartbeats_device_time
    ON device_heartbeats(device_id, received_at DESC);

CREATE INDEX IF NOT EXISTS idx_detections_time
    ON detections(detected_at DESC);

CREATE INDEX IF NOT EXISTS idx_detections_class
    ON detections(class_name);

CREATE INDEX IF NOT EXISTS idx_cleaning_sessions_time
    ON cleaning_sessions(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_cleaning_sessions_status
    ON cleaning_sessions(session_status);

CREATE INDEX IF NOT EXISTS idx_robot_commands_status
    ON robot_commands(command_status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_activity_logs_time
    ON activity_logs(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_telemetry_device_time
    ON device_telemetry(device_id, measured_at DESC);

