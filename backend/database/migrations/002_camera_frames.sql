-- Stores every processed camera frame, including frames with no spill detection.
-- This lets the automatic logic validate consecutive frames rather than counting stale detections.
CREATE TABLE IF NOT EXISTS camera_frames (
    frame_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_device_id BIGINT NOT NULL
        REFERENCES devices(device_id) ON DELETE CASCADE,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    image_path TEXT,
    has_spill BOOLEAN NOT NULL DEFAULT FALSE,
    highest_spill_confidence NUMERIC(5,4)
        CHECK (highest_spill_confidence IS NULL OR highest_spill_confidence BETWEEN 0 AND 1),
    model_name VARCHAR(100),
    model_version VARCHAR(50),
    inference_ms INTEGER CHECK (inference_ms IS NULL OR inference_ms >= 0),
    processed BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE detections
    ADD COLUMN IF NOT EXISTS frame_id BIGINT
    REFERENCES camera_frames(frame_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_camera_frames_camera_time
    ON camera_frames(camera_device_id, captured_at DESC);

CREATE INDEX IF NOT EXISTS idx_detections_frame_id
    ON detections(frame_id);
